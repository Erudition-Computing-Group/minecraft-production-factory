"""Create GitHub Issues from factory run output (agent ticket automation).

Usage:
    python scripts/create_issues.py --run-id <id> [--token <pat>]

Requires: PyGithub, a valid GitHub PAT with repo+issues scope.
"""
import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description="Create GitHub Issues from factory run")
    parser.add_argument("--run-id", required=True, help="Factory run ID")
    parser.add_argument("--token", default=os.environ.get("GH_PAT"), help="GitHub PAT")
    parser.add_argument("--repo", default="Erudition-Computing-Group/minecraft-production-factory",
                        help="GitHub repo (owner/name)")
    args = parser.parse_args()

    if not args.token:
        print("Error: No token provided. Set GH_PAT env var or use --token.")
        sys.exit(1)

    try:
        from github import Github
    except ImportError:
        print("Error: PyGithub not installed. Run: pip install PyGithub")
        sys.exit(1)

    gh = Github(args.token)
    repo = gh.get_repo(args.repo)

    # Load run state
    state_path = ROOT / "memory" / "episodic" / "active_runs" / f"{args.run_id}.json"
    if not state_path.exists():
        print(f"Error: Run state not found at {state_path}")
        sys.exit(1)

    with open(state_path) as f:
        state = json.load(f)

    ideas = state.get("ideas", [])
    created = []

    for idea in ideas:
        # Create [SPEC] issue
        issue = repo.create_issue(
            title=f"[SPEC] {idea}",
            body=f"## Theme & visuals\n{idea}\n\n## Status\nGenerated by factory run `{args.run_id}`\n",
            labels=["status:spec-ready"],
        )
        created.append(issue.number)
        print(f"Created issue #{issue.number}: [SPEC] {idea}")

    print(f"\nCreated {len(created)} issues for run {args.run_id}")
    print(f"Issue numbers: {created}")


if __name__ == "__main__":
    main()
